var ErrInvalidRegistration = errors.New("invalid device registration")
var ErrUserUnavailable = errors.New("user unavailable")

type Registration struct {
	Name          string `json:"name"`
	MachineName   string `json:"machine_name"`
	Platform      string `json:"platform"`
	ClientVersion string `json:"client_version"`
	DeviceCode    string `json:"device_code"`
}

type Device struct {
	ID            int64     `json:"id"`
	Name          string    `json:"name"`
	MachineName   string    `json:"machine_name"`
	Platform      string    `json:"platform"`
	ClientVersion string    `json:"client_version"`
	Status        string    `json:"status"`
	CreatedAt     time.Time `json:"created_at"`
}

type CredentialResult struct {
	Device     Device `json:"device"`
	Credential string `json:"credential"`
}

type Principal struct {
	DeviceID int64
	OwnerID  int64
	Name     string
}

type Store struct {
	pool *pgxpool.Pool
}

func Open(ctx context.Context, databaseURL string) (*Store, error) {
	pool, err := pgxpool.New(ctx, databaseURL)
	if err != nil {
		return nil, fmt.Errorf("configure device database connection: %w", err)
	}
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("connect device store to PostgreSQL: %w", err)
	}
	return &Store{pool: pool}, nil
}

func (store *Store) Close() {
	store.pool.Close()
}

func (store *Store) EnsureSchema(ctx context.Context) error {
	const schema = `
CREATE TABLE IF NOT EXISTS devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    machine_name TEXT NOT NULL,
    platform TEXT NOT NULL,
    client_version TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'REVOKED')),
    last_seen_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS devices_user_created_idx ON devices (user_id, created_at DESC);
CREATE TABLE IF NOT EXISTS pair_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO pair_groups (owner_user_id)
SELECT id FROM users
ON CONFLICT (owner_user_id) DO NOTHING;
ALTER TABLE devices ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS pair_group_id BIGINT REFERENCES pair_groups(id) ON DELETE SET NULL;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS device_code_hash BYTEA NULL;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS credential_hash BYTEA NULL;
UPDATE devices AS d
SET pair_group_id = g.id
FROM pair_groups AS g
WHERE g.owner_user_id = d.user_id AND d.pair_group_id IS NULL;
CREATE INDEX IF NOT EXISTS devices_pair_group_idx ON devices (pair_group_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS devices_code_hash_unique_idx ON devices (device_code_hash) WHERE device_code_hash IS NOT NULL;
CREATE TABLE IF NOT EXISTS pairing_requests (
    id UUID PRIMARY KEY,
    requester_device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    target_device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    requester_code TEXT NOT NULL,
    source_address TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'EXPIRED')),
    expires_at TIMESTAMPTZ NOT NULL,
    decided_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (requester_device_id <> target_device_id)
);
ALTER TABLE pairing_requests ADD COLUMN IF NOT EXISTS requester_code TEXT NOT NULL DEFAULT '';
ALTER TABLE pairing_requests ADD COLUMN IF NOT EXISTS source_address TEXT NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS pairing_requests_target_pending_idx ON pairing_requests (target_device_id, created_at DESC) WHERE status = 'PENDING';
CREATE TABLE IF NOT EXISTS device_pairings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_group_id BIGINT NOT NULL REFERENCES pair_groups(id) ON DELETE CASCADE,
    device_a_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    device_b_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ NULL,
    CHECK (device_a_id <> device_b_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS device_pairings_active_pair_idx ON device_pairings (LEAST(device_a_id, device_b_id), GREATEST(device_a_id, device_b_id)) WHERE revoked_at IS NULL;
`
	if _, err := store.pool.Exec(ctx, schema); err != nil {
		return fmt.Errorf("create devices schema: %w", err)
	}
	return nil
}

func NormalizeRegistration(registration Registration) (Registration, error) {
	registration.Name = strings.TrimSpace(registration.Name)
	registration.MachineName = strings.TrimSpace(registration.MachineName)
	registration.Platform = strings.ToLower(strings.TrimSpace(registration.Platform))
	registration.ClientVersion = strings.TrimSpace(registration.ClientVersion)
	registration.DeviceCode = strings.ToUpper(strings.TrimSpace(registration.DeviceCode))
	if utf8.RuneCountInString(registration.Name) == 0 || utf8.RuneCountInString(registration.Name) > 100 ||
		utf8.RuneCountInString(registration.MachineName) == 0 || utf8.RuneCountInString(registration.MachineName) > 255 ||
		registration.Platform != "windows" || utf8.RuneCountInString(registration.ClientVersion) == 0 || utf8.RuneCountInString(registration.ClientVersion) > 64 ||
		(registration.DeviceCode != "" && !validDeviceCode(registration.DeviceCode)) {
		return Registration{}, ErrInvalidRegistration
	}
	return registration, nil
}

func (store *Store) Register(ctx context.Context, userID int64, registration Registration) (Device, error) {
	if userID <= 0 {
		return Device{}, ErrInvalidRegistration
	}
	registration, err := NormalizeRegistration(registration)
	if err != nil {
		return Device{}, err
	}
	if _, err := store.pool.Exec(ctx, `INSERT INTO pair_groups (owner_user_id) SELECT id FROM users WHERE id = $1 AND status = 'ACTIVE' ON CONFLICT (owner_user_id) DO NOTHING`, userID); err != nil {
		return Device{}, fmt.Errorf("ensure account owner group: %w", err)
	}

	var registered Device
	err = store.pool.QueryRow(ctx, `
INSERT INTO devices (user_id, pair_group_id, name, machine_name, platform, client_version, device_code_hash)
SELECT users.id, g.id, $2, $3, $4, $5, $6
FROM users
JOIN pair_groups AS g ON g.owner_user_id = users.id
WHERE users.id = $1 AND users.status = 'ACTIVE'
RETURNING id, name, machine_name, platform, client_version, status, created_at`,
		userID, registration.Name, registration.MachineName, registration.Platform, registration.ClientVersion, hashedDeviceCode(registration.DeviceCode),
	).Scan(&registered.ID, &registered.Name, &registered.MachineName, &registered.Platform, &registered.ClientVersion, &registered.Status, &registered.CreatedAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return Device{}, ErrUserUnavailable
	}
	if err != nil {
		return Device{}, fmt.Errorf("register device: %w", err)
	}
	return registered, nil
}
