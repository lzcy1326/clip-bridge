package accounts

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
)

type Store struct {
	pool *pgxpool.Pool
}

var ErrInvalidCredentials = errors.New("invalid credentials")

type AuthenticatedUser struct {
	ID          int64
	Username    string
	DisplayName string
}

func Open(ctx context.Context, databaseURL string) (*Store, error) {
	pool, err := pgxpool.New(ctx, databaseURL)
	if err != nil {
		return nil, fmt.Errorf("configure PostgreSQL connection: %w", err)
	}
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("connect to PostgreSQL: %w", err)
	}
	return &Store{pool: pool}, nil
}

func (store *Store) Close() {
	store.pool.Close()
}

func (store *Store) EnsureSchema(ctx context.Context) error {
	const schema = `
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    display_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login_at TIMESTAMPTZ NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci_uq ON users (LOWER(username));
`
	if _, err := store.pool.Exec(ctx, schema); err != nil {
		return fmt.Errorf("create users schema: %w", err)
	}
	return nil
}

func (store *Store) CreateUser(ctx context.Context, username, password string) (int64, error) {
	normalizedUsername, err := NormalizeUsername(username)
	if err != nil {
		return 0, err
	}
	passwordHash, err := HashPassword(password)
	if err != nil {
		return 0, err
	}

	var id int64
	err = store.pool.QueryRow(ctx, `
INSERT INTO users (username, password_hash, display_name)
VALUES ($1, $2, $1)
RETURNING id`, normalizedUsername, passwordHash).Scan(&id)
	if err != nil {
		var postgresError *pgconn.PgError
		if errors.As(err, &postgresError) && postgresError.Code == "23505" {
			return 0, fmt.Errorf("username %q already exists", normalizedUsername)
		}
		return 0, fmt.Errorf("create user: %w", err)
	}
	return id, nil
}

func (store *Store) EnsureBootstrapAdmin(ctx context.Context, password string) (bool, error) {
	var exists bool
	if err := store.pool.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM users WHERE LOWER(username) = 'admin')`).Scan(&exists); err != nil {
		return false, fmt.Errorf("check bootstrap admin: %w", err)
	}
	if exists {
		return false, nil
	}

	passwordHash, err := hashBootstrapPassword(password)
	if err != nil {
		return false, err
	}
	result, err := store.pool.Exec(ctx, `
INSERT INTO users (username, password_hash, display_name, role)
VALUES ('admin', $1, 'admin', 'ADMIN')
ON CONFLICT DO NOTHING`, passwordHash)
	if err != nil {
		return false, fmt.Errorf("create bootstrap admin: %w", err)
	}
	return result.RowsAffected() > 0, nil
}

func (store *Store) Authenticate(ctx context.Context, username, password string) (AuthenticatedUser, error) {
	normalizedUsername, err := NormalizeUsername(username)
	if err != nil {
		burnPasswordHash(password)
		return AuthenticatedUser{}, ErrInvalidCredentials
	}

	var user AuthenticatedUser
	var passwordHash string
	var status string
	err = store.pool.QueryRow(ctx, `
SELECT id, username, display_name, password_hash, status
FROM users
WHERE LOWER(username) = $1`, normalizedUsername).Scan(
		&user.ID, &user.Username, &user.DisplayName, &passwordHash, &status,
	)
	if errors.Is(err, pgx.ErrNoRows) {
		burnPasswordHash(password)
		return AuthenticatedUser{}, ErrInvalidCredentials
	}
	if err != nil {
		return AuthenticatedUser{}, fmt.Errorf("load user for authentication: %w", err)
	}
	if !VerifyPassword(password, passwordHash) || status != "ACTIVE" {
		return AuthenticatedUser{}, ErrInvalidCredentials
	}
	if _, err := store.pool.Exec(ctx, `UPDATE users SET last_login_at = NOW() WHERE id = $1`, user.ID); err != nil {
		return AuthenticatedUser{}, fmt.Errorf("update last login: %w", err)
	}
	user.Username = strings.ToLower(user.Username)
	return user, nil
}
